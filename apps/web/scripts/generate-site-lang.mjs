#!/usr/bin/env node
/** Generates public/site-lang.js from marketing-i18n.mjs */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { en, es, STORAGE_KEY } from "./data/marketing-i18n.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, "../public/site-lang.js");

const catalogs = { en, es };
const keyCount = Object.keys(en).length;

const js = `/* Generated by scripts/generate-site-lang.mjs — do not edit. */
(function () {
  var STORAGE_KEY = ${JSON.stringify(STORAGE_KEY)};
  var catalogs = ${JSON.stringify(catalogs, null, 2)};

  function detectLocale() {
    // A real, statically-generated /es/ page sets <html lang="es"> server-side — that's
    // authoritative for THIS page and must win over a stale stored preference, or the
    // client-side swap would flip already-Spanish markup back to English on load. A plain
    // "en" doc-lang is NOT given the same authority — most pages are still English markup
    // with a client-side Spanish overlay, and a stored "es" preference should keep applying
    // as the user navigates between those.
    if (document.documentElement.getAttribute("lang") === "es") {
      try {
        localStorage.setItem(STORAGE_KEY, "es");
      } catch (e) {}
      return "es";
    }
    try {
      var stored = localStorage.getItem(STORAGE_KEY);
      if (stored === "en" || stored === "es") return stored;
    } catch (e) {}
    var nav = typeof navigator !== "undefined" ? navigator.language : "en";
    return nav.toLowerCase().indexOf("es") === 0 ? "es" : "en";
  }

  function interpolate(template, vars) {
    if (!vars) return template;
    return template.replace(/\\{\\{(\\w+)\\}\\}/g, function (_, key) {
      return vars[key] !== undefined ? String(vars[key]) : "{{" + key + "}}";
    });
  }

  var currentLocale = detectLocale();

  function t(key, vars) {
    var catalog = catalogs[currentLocale] || catalogs.en;
    var raw = catalog[key] != null ? catalog[key] : catalogs.en[key];
    return raw != null ? interpolate(raw, vars) : key;
  }

  function applyLocale(locale) {
    currentLocale = locale === "es" ? "es" : "en";
    document.documentElement.lang = currentLocale;
    try {
      localStorage.setItem(STORAGE_KEY, currentLocale);
    } catch (e) {}

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (!key) return;
      var catalog = catalogs[currentLocale] || catalogs.en;
      var raw = catalog[key] != null ? catalog[key] : catalogs.en[key];
      // Keep the HTML fallback when a key is missing (avoids flashing raw keys on stale caches).
      if (raw != null) el.textContent = interpolate(raw);
    });

    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-html");
      if (!key) return;
      var catalog = catalogs[currentLocale] || catalogs.en;
      var raw = catalog[key] != null ? catalog[key] : catalogs.en[key];
      if (raw != null) el.innerHTML = interpolate(raw);
    });

    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-aria");
      if (!key) return;
      var catalog = catalogs[currentLocale] || catalogs.en;
      var raw = catalog[key] != null ? catalog[key] : catalogs.en[key];
      if (raw != null) el.setAttribute("aria-label", interpolate(raw));
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-placeholder");
      if (!key) return;
      var catalog = catalogs[currentLocale] || catalogs.en;
      var raw = catalog[key] != null ? catalog[key] : catalogs.en[key];
      if (raw != null) el.setAttribute("placeholder", interpolate(raw));
    });

    var year = String(new Date().getFullYear());
    document.querySelectorAll("[data-i18n-year]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-year");
      if (!key) return;
      var catalog = catalogs[currentLocale] || catalogs.en;
      var raw = catalog[key] != null ? catalog[key] : catalogs.en[key];
      if (raw != null) el.textContent = interpolate(raw, { year: year });
    });

    document.querySelectorAll(".locale-switch").forEach(function (wrap) {
      var code = wrap.querySelector("[data-locale-code]");
      if (code) code.textContent = currentLocale.toUpperCase();
      wrap.querySelectorAll("button[data-locale]").forEach(function (btn) {
        var active = btn.getAttribute("data-locale") === currentLocale;
        btn.classList.toggle("is-active", active);
        btn.setAttribute("aria-selected", active ? "true" : "false");
      });
    });
  }

  var LOCALE_NAMES = { en: "lang.english", es: "lang.spanish" };
  var GLOBE_SVG =
    '<svg class="locale-switch-globe" width="16" height="16" viewBox="0 0 24 24" aria-hidden="true">' +
    '<circle cx="12" cy="12" r="9" fill="none" stroke="currentColor" stroke-width="1.6" />' +
    '<path d="M3 12h18M12 3c2.5 2.8 3.8 5.8 3.8 9s-1.3 6.2-3.8 9c-2.5-2.8-3.8-5.8-3.8-9S9.5 5.8 12 3z" fill="none" stroke="currentColor" stroke-width="1.6" /></svg>';
  var CHEVRON_SVG =
    '<svg class="locale-switch-chevron" width="12" height="12" viewBox="0 0 12 12" aria-hidden="true">' +
    '<path d="M2.5 4.5L6 8l3.5-3.5" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" /></svg>';

  function renderLocaleSwitcher(container) {
    if (!container || container.querySelector("[data-locale-trigger]")) return;
    container.setAttribute("role", "group");
    container.setAttribute("data-i18n-aria", "nav.language");

    var trigger = document.createElement("button");
    trigger.type = "button";
    trigger.className = "locale-switch-trigger";
    trigger.setAttribute("data-locale-trigger", "");
    trigger.setAttribute("aria-haspopup", "listbox");
    trigger.setAttribute("aria-expanded", "false");
    trigger.innerHTML =
      GLOBE_SVG + '<span class="locale-switch-code" data-locale-code>EN</span>' + CHEVRON_SVG;

    var menu = document.createElement("ul");
    menu.className = "locale-switch-menu";
    menu.setAttribute("role", "listbox");
    menu.setAttribute("data-locale-menu", "");
    menu.hidden = true;

    ["en", "es"].forEach(function (code) {
      var li = document.createElement("li");
      li.setAttribute("role", "option");
      var opt = document.createElement("button");
      opt.type = "button";
      opt.className = "locale-switch-option";
      opt.setAttribute("data-locale", code);
      var codeSpan = document.createElement("span");
      codeSpan.className = "locale-switch-option-code";
      codeSpan.textContent = code.toUpperCase();
      var nameSpan = document.createElement("span");
      nameSpan.className = "locale-switch-option-name";
      nameSpan.setAttribute("data-i18n", LOCALE_NAMES[code]);
      nameSpan.textContent = code === "en" ? "English" : "Español";
      opt.appendChild(codeSpan);
      opt.appendChild(nameSpan);
      li.appendChild(opt);
      menu.appendChild(li);
    });

    container.appendChild(trigger);
    container.appendChild(menu);
  }

  function closeAllLocaleMenus(except) {
    document.querySelectorAll(".locale-switch").forEach(function (wrap) {
      if (wrap === except) return;
      var menu = wrap.querySelector("[data-locale-menu]");
      var trigger = wrap.querySelector("[data-locale-trigger]");
      var chevron = wrap.querySelector(".locale-switch-chevron");
      if (menu) menu.hidden = true;
      if (trigger) trigger.setAttribute("aria-expanded", "false");
      if (chevron) chevron.classList.remove("is-open");
      wrap.classList.remove("is-open");
    });
  }

  function wireLocaleSwitchers() {
    document.querySelectorAll("[data-locale-switch]").forEach(renderLocaleSwitcher);

    document.querySelectorAll(".locale-switch").forEach(function (wrap) {
      if (wrap.__chasaLocaleWired) return;
      wrap.__chasaLocaleWired = true;

      var trigger = wrap.querySelector("[data-locale-trigger]");
      var menu = wrap.querySelector("[data-locale-menu]");
      var chevron = wrap.querySelector(".locale-switch-chevron");
      if (!trigger || !menu) return;

      trigger.addEventListener("click", function (e) {
        e.stopPropagation();
        var open = !menu.hidden;
        closeAllLocaleMenus(wrap);
        menu.hidden = open;
        trigger.setAttribute("aria-expanded", open ? "false" : "true");
        if (chevron) chevron.classList.toggle("is-open", !open);
        wrap.classList.toggle("is-open", !open);
      });

      wrap.querySelectorAll("button[data-locale]").forEach(function (btn) {
        btn.addEventListener("click", function () {
          var loc = btn.getAttribute("data-locale");
          if (loc === "es" && wrap.hasAttribute("data-es-href")) {
            // Without this, the target page's own client-side swap would read the OLD
            // stored preference on load and immediately flip back.
            try {
              localStorage.setItem(STORAGE_KEY, "es");
            } catch (e) {}
            window.location.href = wrap.getAttribute("data-es-href");
            return;
          }
          if (loc === "en" && wrap.hasAttribute("data-en-href")) {
            try {
              localStorage.setItem(STORAGE_KEY, "en");
            } catch (e) {}
            window.location.href = wrap.getAttribute("data-en-href");
            return;
          }
          if (loc === "en" || loc === "es") applyLocale(loc);
          closeAllLocaleMenus();
        });
      });
    });

    document.addEventListener("click", function () {
      closeAllLocaleMenus();
    });
    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape") closeAllLocaleMenus();
    });
  }

  function init() {
    wireLocaleSwitchers();
    applyLocale(currentLocale);
  }

  window.chasaSiteLang = {
    locale: function () { return currentLocale; },
    setLocale: applyLocale,
    t: t,
    apply: function () { applyLocale(currentLocale); },
  };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
`;

writeFileSync(outPath, js, "utf8");
console.log(`Generated site-lang.js (${keyCount} keys × 2 locales)`);
