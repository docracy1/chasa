#!/usr/bin/env node
/** Generates public/site-lang.js from marketing-i18n.mjs */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { en, es, STORAGE_KEY } from "./data/marketing-i18n.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, "../public/site-lang.js");

const catalogs = { en, es };
const keyCount = Object.keys(en).length;

const js = `/* Generated by scripts/generate-site-lang.mjs — do not edit. */
(function () {
  var STORAGE_KEY = ${JSON.stringify(STORAGE_KEY)};
  var catalogs = ${JSON.stringify(catalogs, null, 2)};

  function detectLocale() {
    try {
      var stored = localStorage.getItem(STORAGE_KEY);
      if (stored === "en" || stored === "es") return stored;
    } catch (e) {}
    var nav = typeof navigator !== "undefined" ? navigator.language : "en";
    return nav.toLowerCase().indexOf("es") === 0 ? "es" : "en";
  }

  function interpolate(template, vars) {
    if (!vars) return template;
    return template.replace(/\\{\\{(\\w+)\\}\\}/g, function (_, key) {
      return vars[key] !== undefined ? String(vars[key]) : "{{" + key + "}}";
    });
  }

  var currentLocale = detectLocale();

  function t(key, vars) {
    var catalog = catalogs[currentLocale] || catalogs.en;
    var raw = catalog[key] != null ? catalog[key] : catalogs.en[key];
    return raw != null ? interpolate(raw, vars) : key;
  }

  function applyLocale(locale) {
    currentLocale = locale === "es" ? "es" : "en";
    document.documentElement.lang = currentLocale;
    try {
      localStorage.setItem(STORAGE_KEY, currentLocale);
    } catch (e) {}

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (!key) return;
      var catalog = catalogs[currentLocale] || catalogs.en;
      var raw = catalog[key] != null ? catalog[key] : catalogs.en[key];
      // Keep the HTML fallback when a key is missing (avoids flashing raw keys on stale caches).
      if (raw != null) el.textContent = interpolate(raw);
    });

    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-html");
      if (!key) return;
      var catalog = catalogs[currentLocale] || catalogs.en;
      var raw = catalog[key] != null ? catalog[key] : catalogs.en[key];
      if (raw != null) el.innerHTML = interpolate(raw);
    });

    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-aria");
      if (!key) return;
      var catalog = catalogs[currentLocale] || catalogs.en;
      var raw = catalog[key] != null ? catalog[key] : catalogs.en[key];
      if (raw != null) el.setAttribute("aria-label", interpolate(raw));
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-placeholder");
      if (!key) return;
      var catalog = catalogs[currentLocale] || catalogs.en;
      var raw = catalog[key] != null ? catalog[key] : catalogs.en[key];
      if (raw != null) el.setAttribute("placeholder", interpolate(raw));
    });

    var year = String(new Date().getFullYear());
    document.querySelectorAll("[data-i18n-year]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-year");
      if (!key) return;
      var catalog = catalogs[currentLocale] || catalogs.en;
      var raw = catalog[key] != null ? catalog[key] : catalogs.en[key];
      if (raw != null) el.textContent = interpolate(raw, { year: year });
    });

    document.querySelectorAll(".locale-switch").forEach(function (wrap) {
      wrap.querySelectorAll("button[data-locale]").forEach(function (btn) {
        var active = btn.getAttribute("data-locale") === currentLocale;
        btn.classList.toggle("is-active", active);
        btn.setAttribute("aria-pressed", active ? "true" : "false");
      });
    });
  }

  function renderLocaleSwitcher(container) {
    if (!container || container.querySelector("button[data-locale]")) return;
    container.setAttribute("role", "group");
    container.setAttribute("data-i18n-aria", "nav.language");

    var enBtn = document.createElement("button");
    enBtn.type = "button";
    enBtn.setAttribute("data-locale", "en");
    enBtn.textContent = "EN";

    var sep = document.createElement("span");
    sep.className = "locale-switch-sep";
    sep.setAttribute("aria-hidden", "true");
    sep.textContent = "|";

    var esBtn = document.createElement("button");
    esBtn.type = "button";
    esBtn.setAttribute("data-locale", "es");
    esBtn.textContent = "ES";

    container.appendChild(enBtn);
    container.appendChild(sep);
    container.appendChild(esBtn);
  }

  function wireLocaleSwitchers() {
    document.querySelectorAll("[data-locale-switch]").forEach(renderLocaleSwitcher);

    document.querySelectorAll(".locale-switch button[data-locale]").forEach(function (btn) {
      if (btn.__chasaLocaleWired) return;
      btn.__chasaLocaleWired = true;
      btn.addEventListener("click", function () {
        var loc = btn.getAttribute("data-locale");
        if (loc === "en" || loc === "es") applyLocale(loc);
      });
    });
  }

  function init() {
    wireLocaleSwitchers();
    applyLocale(currentLocale);
  }

  window.chasaSiteLang = {
    locale: function () { return currentLocale; },
    setLocale: applyLocale,
    t: t,
    apply: function () { applyLocale(currentLocale); },
  };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
`;

writeFileSync(outPath, js, "utf8");
console.log(`Generated site-lang.js (${keyCount} keys × 2 locales)`);
